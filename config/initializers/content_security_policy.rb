# Política de seguridad de contenido (CSP): el navegador solo ejecuta scripts y estilos
# servidos por la propia app. El importmap en línea lleva un nonce por petición.
# Chart.js está descargado en vendor/javascript, así que no hace falta permitir ningún CDN.
Rails.application.configure do
  config.content_security_policy do |policy|
    policy.default_src :self
    policy.script_src  :self
    policy.style_src   :self
    policy.img_src     :self, :data
    policy.font_src    :self
    policy.connect_src :self
    policy.object_src  :none
    policy.base_uri    :self
    policy.form_action :self
    policy.frame_ancestors :none
  end

  config.content_security_policy_nonce_generator = ->(_request) { SecureRandom.base64(16) }
  config.content_security_policy_nonce_directives = %w[script-src]
end
